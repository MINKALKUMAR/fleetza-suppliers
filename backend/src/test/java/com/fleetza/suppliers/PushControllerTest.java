package com.fleetza.suppliers;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fleetza.suppliers.dto.request.LoginRequest;
import com.fleetza.suppliers.dto.request.PushSubscriptionRequest;
import nl.martijndwars.webpush.Utils;
import org.bouncycastle.jce.provider.BouncyCastleProvider;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.TestPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

import java.security.Security;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("dev")
@TestPropertySource(properties = {
        "app.vapid.public-key=BIiFbsJ66gCAKout54Ghilbm4lTVRpHu1rctE69Vkj7YkGRQKWMCVyzA3FMItI1A-AJaVxXWuacsZBsaBj-YzlA",
        "app.vapid.private-key=JWDy6nNblYU09Pozllon3VNmb3XE_zP2jmue66hV45k",
        "app.vapid.subject=mailto:test@fleetza.in"
})
class PushControllerTest {

    private static final String TEST_PUBLIC_KEY =
            "BIiFbsJ66gCAKout54Ghilbm4lTVRpHu1rctE69Vkj7YkGRQKWMCVyzA3FMItI1A-AJaVxXWuacsZBsaBj-YzlA";
    private static final String TEST_PRIVATE_KEY =
            "JWDy6nNblYU09Pozllon3VNmb3XE_zP2jmue66hV45k";

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private ObjectMapper objectMapper;

    @Test
    @DisplayName("Should parse base64url VAPID keypair generated by deploy/generate-vapid-keys.mjs")
    void testVapidKeyCompatibility() throws Exception {
        if (Security.getProvider(BouncyCastleProvider.PROVIDER_NAME) == null) {
            Security.addProvider(new BouncyCastleProvider());
        }
        assertNotNull(Utils.loadPublicKey(TEST_PUBLIC_KEY));
        assertNotNull(Utils.loadPrivateKey(TEST_PRIVATE_KEY));
    }

    @Test
    @DisplayName("Should expose public VAPID configuration without authentication")
    void testPublicVapidKeyEndpoint() throws Exception {
        mockMvc.perform(get("/api/push/vapid-public-key"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.configured").value(true))
                .andExpect(jsonPath("$.data.publicKey").value(TEST_PUBLIC_KEY));
    }

    @Test
    @DisplayName("Should reject unauthenticated push status and subscribe requests")
    void testPushEndpointsRequireAuth() throws Exception {
        mockMvc.perform(get("/api/push/status"))
                .andExpect(status().isUnauthorized());

        mockMvc.perform(post("/api/push/subscribe")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{}"))
                .andExpect(status().isUnauthorized());
    }

    @Test
    @DisplayName("Should subscribe, report status, and unsubscribe a Web Push browser endpoint")
    void testSubscribeAndUnsubscribeLifecycle() throws Exception {
        LoginRequest loginRequest = new LoginRequest("admin", "Admin@12345");
        MvcResult loginResult = mockMvc.perform(post("/api/auth/login")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(loginRequest)))
                .andExpect(status().isOk())
                .andReturn();

        String token = objectMapper.readTree(loginResult.getResponse().getContentAsString())
                .get("data").get("accessToken").asText();

        String endpoint = "https://fcm.googleapis.com/fcm/send/test-endpoint-fleetza-001";
        PushSubscriptionRequest.Keys keys = new PushSubscriptionRequest.Keys();
        keys.setP256dh("BEl62iUYgUivxIkv69yViEuiBIa-Ib9-SkvMeAtA3LFgDzkrxZJjSgSnfckjBJuBkr3qBUYIHBQFLXYp5Nksh8");
        keys.setAuth("tBHItJI5svbpez7KI4CCXg");

        PushSubscriptionRequest req = new PushSubscriptionRequest();
        req.setEndpoint(endpoint);
        req.setKeys(keys);
        req.setUserAgent("Mozilla/5.0 TestBrowser");

        mockMvc.perform(post("/api/push/subscribe")
                        .header("Authorization", "Bearer " + token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(req)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.subscribedDevices").value(1))
                .andExpect(jsonPath("$.data.configured").value(true));

        mockMvc.perform(get("/api/push/status")
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.configured").value(true))
                .andExpect(jsonPath("$.data.subscribedDevices").value(1));

        mockMvc.perform(post("/api/push/unsubscribe")
                        .header("Authorization", "Bearer " + token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(Map.of("endpoint", endpoint))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true));

        mockMvc.perform(get("/api/push/status")
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.subscribedDevices").value(0));
    }
}

